async fn insert_result(
    connection: &mut PgConnection,
    dataset_id: i32,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query("INSERT INTO user_test_results (user_test_id, dataset_id) VALUES ($1, $2)")
        .bind(USER_TEST)
        .bind(dataset_id)
        .execute(connection)
        .await
}

async fn insert_executable(
    connection: &mut PgConnection,
    dataset_id: i32,
    filename: &str,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO user_test_executables \
         (user_test_id, dataset_id, filename, digest) VALUES ($1, $2, $3, $4)",
    )
    .bind(USER_TEST)
    .bind(dataset_id)
    .bind(filename)
    .bind(digest().as_str())
    .execute(connection)
    .await
}

#[tokio::test]
async fn a_repeated_file_filename_is_refused_by_the_database() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    insert_file(connection.connection(), "input.%l")
        .await
        .expect("first file");

    let refused = insert_file(connection.connection(), "input.%l").await;
    assert_eq!(code_of(&refused).as_deref(), Some("23505"));
}

