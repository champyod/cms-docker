//! The contest window and token checks against a real server.
//!
//! WHY live: the refusals are Postgres `CheckConstraint`s, so the proof that
//! this port refuses exactly what the reference refuses is the server refusing
//! the same `INSERT`. Each table is `TEMP`, so a run leaves the scratch database
//! as it found it.
//!
//! The suite runs when `CMS_DB_TEST_URL` names a scratch database and skips
//! otherwise, which is why the skip message is printed: a skip reported as a
//! pass proves nothing.
//!
//! RUN: CMS_DB_TEST_URL=postgres://cmsuser:***@127.0.0.1:5432/cmsdb_test \
//!        cargo test -p cms-db --test contest_live

use chrono::{NaiveDate, NaiveDateTime};
use cms_db::{
    ContestWindow, DedicatedConnection, Interval, Phase, SessionConfig, TokenMode, TokenPolicy,
};
use sqlx::postgres::{PgConnection, PgQueryResult};
use sqlx::Row;

const URL_ENV: &str = "CMS_DB_TEST_URL";

/// The three stored modes, created once per scratch database.
const CREATE_TYPE: &str = "\
    DO $$ BEGIN \
        CREATE TYPE token_mode AS ENUM ('disabled', 'finite', 'infinite'); \
    EXCEPTION WHEN duplicate_object THEN NULL; \
    END $$";

/// `contests` with the columns and checks this suite exercises.
const CREATE_CONTESTS: &str = "\
    CREATE TEMP TABLE contests (\
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
        name text NOT NULL UNIQUE, \
        start timestamp NOT NULL, \
        stop timestamp NOT NULL, \
        analysis_enabled boolean NOT NULL, \
        analysis_start timestamp NOT NULL, \
        analysis_stop timestamp NOT NULL, \
        token_mode token_mode NOT NULL DEFAULT 'infinite', \
        token_max_number integer CHECK (token_max_number > 0), \
        token_min_interval interval NOT NULL DEFAULT interval '0 seconds' \
            CHECK (token_min_interval >= interval '0 seconds'), \
        token_gen_initial integer NOT NULL DEFAULT 2 \
            CHECK (token_gen_initial >= 0), \
        token_gen_number integer NOT NULL DEFAULT 2 \
            CHECK (token_gen_number >= 0), \
        token_gen_interval interval NOT NULL DEFAULT interval '30 minutes' \
            CHECK (token_gen_interval > interval '0 seconds'), \
        token_gen_max integer CHECK (token_gen_max > 0), \
        CHECK (start <= stop), \
        CHECK (stop <= analysis_start), \
        CHECK (analysis_start <= analysis_stop), \
        CHECK (token_gen_initial <= token_gen_max))";

/// Serialises the one catalogue write every test shares; the DO block's handler
/// catches the already-exists error, not the unique-index race two connections
/// can hit at once.
const LOCK_TYPE: &str = "SELECT pg_advisory_lock(918273)";
const UNLOCK_TYPE: &str = "SELECT pg_advisory_unlock(918273)";

fn skip() -> Option<SessionConfig> {
    let config = std::env::var(URL_ENV)
        .ok()
        .filter(|url| !url.trim().is_empty())
        .map(SessionConfig::new);
    if config.is_none() {
        eprintln!("SKIP: set {URL_ENV} to a scratch database to run the live half");
    }
    config
}

async fn open(config: &SessionConfig) -> DedicatedConnection {
    let mut connection = DedicatedConnection::open(config)
        .await
        .expect("opening the scratch database");
    for statement in [LOCK_TYPE, CREATE_TYPE, UNLOCK_TYPE, CREATE_CONTESTS] {
        sqlx::query(statement)
            .execute(connection.connection())
            .await
            .expect("creating the contests schema");
    }
    connection
}

/// The SQLSTATE of a refused statement, so a refusal is pinned to its own rule.
fn code_of<T>(result: &Result<T, sqlx::Error>) -> Option<String> {
    result
        .as_ref()
        .err()
        .and_then(sqlx::Error::as_database_error)
        .and_then(|error| error.code())
        .map(|code| code.to_string())
}

/// One instant on the day every fixture sits on.
fn at(hour: u32, minute: u32) -> NaiveDateTime {
    NaiveDate::from_ymd_opt(2026, 11, 22)
        .and_then(|date| date.and_hms_opt(hour, minute, 0))
        .expect("fixture time is valid")
}

/// A contest open from 09:00 to 12:00, with analysis from 13:00 to 14:00.
fn window() -> ContestWindow {
    ContestWindow {
        start: at(9, 0),
        stop: at(12, 0),
        analysis_enabled: true,
        analysis_start: at(13, 0),
        analysis_stop: at(14, 0),
    }
}

/// A policy inside every token check.
fn policy() -> TokenPolicy {
    TokenPolicy {
        mode: TokenMode::Finite,
        max_number: Some(10),
        min_interval: Interval::from_seconds(60).expect("fixture interval"),
        gen_initial: 2,
        gen_number: 1,
        gen_interval: Interval::from_seconds(600).expect("fixture interval"),
        gen_max: Some(4),
    }
}

async fn insert_window(
    connection: &mut PgConnection,
    name: &str,
    window: &ContestWindow,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO contests \
         (name, start, stop, analysis_enabled, analysis_start, analysis_stop) \
         VALUES ($1, $2, $3, $4, $5, $6)",
    )
    .bind(name)
    .bind(window.start)
    .bind(window.stop)
    .bind(window.analysis_enabled)
    .bind(window.analysis_start)
    .bind(window.analysis_stop)
    .execute(connection)
    .await
}

async fn insert_policy(
    connection: &mut PgConnection,
    name: &str,
    policy: &TokenPolicy,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO contests \
         (name, start, stop, analysis_enabled, analysis_start, analysis_stop, \
          token_mode, token_max_number, token_min_interval, token_gen_initial, \
          token_gen_number, token_gen_interval, token_gen_max) \
         VALUES ($1, timestamp '2026-11-22 09:00', timestamp '2026-11-22 12:00', false, \
                 timestamp '2026-11-22 13:00', timestamp '2026-11-22 14:00', \
                 $2::token_mode, $3, $4, $5, $6, $7, $8)",
    )
    .bind(name)
    .bind(policy.mode.as_str())
    .bind(policy.max_number)
    .bind(policy.min_interval.to_pg().expect("fixture interval fits"))
    .bind(policy.gen_initial)
    .bind(policy.gen_number)
    .bind(policy.gen_interval.to_pg().expect("fixture interval fits"))
    .bind(policy.gen_max)
    .execute(connection)
    .await
}

#[tokio::test]
async fn a_stored_window_reads_back_and_phases_as_the_reference_does() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    let fixture = window();

    insert_window(connection.connection(), "read-back", &fixture)
        .await
        .expect("the database accepts a valid window");

    let row = sqlx::query(
        "SELECT start, stop, analysis_enabled, analysis_start, analysis_stop \
         FROM contests WHERE name = 'read-back'",
    )
    .fetch_one(connection.connection())
    .await
    .expect("reading the window back");
    let stored = ContestWindow {
        start: row.try_get("start").expect("start timestamp"),
        stop: row.try_get("stop").expect("stop timestamp"),
        analysis_enabled: row.try_get("analysis_enabled").expect("flag"),
        analysis_start: row.try_get("analysis_start").expect("analysis start"),
        analysis_stop: row.try_get("analysis_stop").expect("analysis stop"),
    };

    assert_eq!(stored, fixture);
    assert_eq!(stored.phase(at(8, 59)), Phase::NotStarted);
    assert_eq!(stored.phase(at(9, 0)), Phase::Active);
    assert_eq!(stored.phase(at(12, 0)), Phase::Active);
    assert_eq!(stored.phase(at(12, 1)), Phase::WaitingForAnalysis);
    assert_eq!(stored.phase(at(13, 0)), Phase::Analysis);
    assert_eq!(stored.phase(at(14, 0)), Phase::Analysis);
    assert_eq!(stored.phase(at(14, 1)), Phase::Ended);
}

#[tokio::test]
async fn the_database_refuses_the_window_orderings_the_validator_refuses() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    let mut cases = Vec::new();
    let mut backwards = window();
    backwards.stop = at(8, 0);
    cases.push(("stop-before-start", backwards));
    let mut analysis_before_stop = window();
    analysis_before_stop.analysis_start = at(11, 0);
    cases.push(("analysis-before-stop", analysis_before_stop));
    let mut analysis_backwards = window();
    analysis_backwards.analysis_stop = at(12, 30);
    cases.push(("analysis-backwards", analysis_backwards));

    for (name, case) in cases {
        assert!(case.validate().is_err(), "{name} passed the validator");
        let refused = insert_window(connection.connection(), name, &case).await;
        assert_eq!(
            code_of(&refused).as_deref(),
            Some("23514"),
            "the database accepted {name}"
        );
    }
}

#[tokio::test]
async fn the_database_refuses_the_token_configurations_the_validator_refuses() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    let mut cases = Vec::new();
    cases.push((
        "zero-total-cap",
        TokenPolicy {
            max_number: Some(0),
            ..policy()
        },
    ));
    cases.push((
        "negative-min-interval",
        TokenPolicy {
            min_interval: Interval::from_seconds(-1).expect("fixture interval"),
            ..policy()
        },
    ));
    cases.push((
        "negative-initial",
        TokenPolicy {
            gen_initial: -1,
            ..policy()
        },
    ));
    cases.push((
        "negative-generation",
        TokenPolicy {
            gen_number: -1,
            ..policy()
        },
    ));
    cases.push((
        "zero-generation-interval",
        TokenPolicy {
            gen_interval: Interval::zero(),
            ..policy()
        },
    ));
    cases.push((
        "zero-generation-cap",
        TokenPolicy {
            gen_max: Some(0),
            ..policy()
        },
    ));
    cases.push((
        "initial-above-cap",
        TokenPolicy {
            gen_initial: 5,
            gen_max: Some(4),
            ..policy()
        },
    ));

    for (name, case) in cases {
        assert!(case.validate().is_err(), "{name} passed the validator");
        let refused = insert_policy(connection.connection(), name, &case).await;
        assert_eq!(
            code_of(&refused).as_deref(),
            Some("23514"),
            "the database accepted {name}"
        );
    }
}

#[tokio::test]
async fn the_database_refuses_a_mode_outside_the_enum() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;

    assert!("mixed".parse::<TokenMode>().is_err());
    let refused = sqlx::query(
        "INSERT INTO contests \
         (name, start, stop, analysis_enabled, analysis_start, analysis_stop, token_mode) \
         VALUES ('mixed', timestamp '2026-11-22 09:00', timestamp '2026-11-22 12:00', false, \
                 timestamp '2026-11-22 13:00', timestamp '2026-11-22 14:00', 'mixed')",
    )
    .execute(connection.connection())
    .await;

    assert!(refused.is_err(), "the enum accepted `mixed`");
    assert_eq!(code_of(&refused).as_deref(), Some("22P02"));
}

#[tokio::test]
async fn the_database_accepts_a_valid_finite_policy() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    let fixture = policy();

    assert_eq!(fixture.validate(), Ok(()));
    insert_policy(connection.connection(), "finite", &fixture)
        .await
        .expect("the database accepts a valid finite policy");
}

#[tokio::test]
async fn the_database_does_not_bound_an_absent_generation_cap() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    let fixture = TokenPolicy {
        gen_initial: 99,
        gen_max: None,
        ..policy()
    };

    assert_eq!(fixture.validate(), Ok(()));
    insert_policy(connection.connection(), "uncapped", &fixture)
        .await
        .expect("a NULL cap makes the check unknown, not false");
}
