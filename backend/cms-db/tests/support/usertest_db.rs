//! The user-test scratch schema, seeds and inserts the live suites share.

use cms_db::{DedicatedConnection, FileDigest, SessionConfig};
use sqlx::postgres::{PgConnection, PgQueryResult};

/// The environment variable naming the scratch database.
pub const URL_ENV: &str = "CMS_DB_TEST_URL";

/// Forty lowercase hex characters, which the `DIGEST` check accepts.
pub const DIGEST: &str = "0123456789abcdef0123456789abcdef01234567";

/// The user test and the two datasets every fixture names.
pub const USER_TEST: i32 = 7;
pub const DATASET: i32 = 9;
pub const OTHER_DATASET: i32 = 10;

/// The five tables, with the constraints the rules module reproduces.
const SCHEMA: [&str; 6] = [
    "CREATE TEMP TABLE user_tests (id integer PRIMARY KEY, task_id integer NOT NULL)",
    "CREATE TEMP TABLE datasets (id integer PRIMARY KEY, task_id integer NOT NULL)",
    "CREATE TEMP TABLE user_test_files (\
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
        user_test_id integer NOT NULL REFERENCES user_tests(id) ON DELETE CASCADE, \
        filename varchar NOT NULL \
            CHECK (filename ~ '^[A-Za-z0-9_.-]+(.%l)?$') \
            CHECK (filename != '.') CHECK (filename != '..'), \
        digest varchar NOT NULL CHECK (digest ~ '^([0-9a-f]{40}|x)$'), \
        UNIQUE (user_test_id, filename))",
    "CREATE TEMP TABLE user_test_managers (\
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
        user_test_id integer NOT NULL REFERENCES user_tests(id) ON DELETE CASCADE, \
        filename varchar NOT NULL \
            CHECK (filename ~ '^[A-Za-z0-9_.-]+$') \
            CHECK (filename != '.') CHECK (filename != '..'), \
        digest varchar NOT NULL CHECK (digest ~ '^([0-9a-f]{40}|x)$'), \
        UNIQUE (user_test_id, filename))",
    "CREATE TEMP TABLE user_test_results (\
        user_test_id integer NOT NULL REFERENCES user_tests(id) ON DELETE CASCADE, \
        dataset_id integer NOT NULL REFERENCES datasets(id) ON DELETE CASCADE, \
        PRIMARY KEY (user_test_id, dataset_id))",
    "CREATE TEMP TABLE user_test_executables (\
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
        user_test_id integer NOT NULL, \
        dataset_id integer NOT NULL, \
        filename varchar NOT NULL, \
        digest varchar NOT NULL, \
        FOREIGN KEY (user_test_id, dataset_id) \
            REFERENCES user_test_results (user_test_id, dataset_id) ON DELETE CASCADE, \
        UNIQUE (user_test_id, dataset_id, filename))",
];

/// The seeds every test needs: one user test and two datasets on its task.
const SEED: [&str; 2] = [
    "INSERT INTO user_tests (id, task_id) VALUES (7, 42)",
    "INSERT INTO datasets (id, task_id) VALUES (9, 42), (10, 42)",
];

/// The scratch database, or a printed skip when none is configured.
pub fn skip() -> Option<SessionConfig> {
    let config = std::env::var(URL_ENV)
        .ok()
        .filter(|url| !url.trim().is_empty())
        .map(SessionConfig::new);
    if config.is_none() {
        eprintln!("SKIP: set {URL_ENV} to a scratch database to run the live half");
    }
    config
}

/// Open the scratch database, create the schema and seed the two keys.
pub async fn open(config: &SessionConfig) -> DedicatedConnection {
    let mut connection = DedicatedConnection::open(config)
        .await
        .expect("opening the scratch database");
    for statement in SCHEMA.iter().chain(SEED.iter()) {
        sqlx::query(*statement)
            .execute(connection.connection())
            .await
            .expect("creating and seeding the user-test schema");
    }
    connection
}

/// A valid fixture digest.
pub fn digest() -> FileDigest {
    DIGEST.parse().expect("fixture digest is valid")
}

/// The SQLSTATE of a refused statement, so a refusal is pinned to its own rule.
pub fn code_of<T>(result: &Result<T, sqlx::Error>) -> Option<String> {
    result
        .as_ref()
        .err()
        .and_then(sqlx::Error::as_database_error)
        .and_then(|error| error.code())
        .map(|code| code.to_string())
}

/// Insert one uploaded file.
pub async fn insert_file(
    connection: &mut PgConnection,
    filename: &str,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO user_test_files (user_test_id, filename, digest) \
         VALUES ($1, $2, $3)",
    )
    .bind(USER_TEST)
    .bind(filename)
    .bind(DIGEST)
    .execute(connection)
    .await
}

/// Insert one manager file.
pub async fn insert_manager(
    connection: &mut PgConnection,
    filename: &str,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO user_test_managers (user_test_id, filename, digest) \
         VALUES ($1, $2, $3)",
    )
    .bind(USER_TEST)
    .bind(filename)
    .bind(DIGEST)
    .execute(connection)
    .await
}

/// Insert one result row.
pub async fn insert_result(
    connection: &mut PgConnection,
    dataset_id: i32,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query("INSERT INTO user_test_results (user_test_id, dataset_id) VALUES ($1, $2)")
        .bind(USER_TEST)
        .bind(dataset_id)
        .execute(connection)
        .await
}

/// Insert one executable.
pub async fn insert_executable(
    connection: &mut PgConnection,
    dataset_id: i32,
    filename: &str,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO user_test_executables \
         (user_test_id, dataset_id, filename, digest) VALUES ($1, $2, $3, $4)",
    )
    .bind(USER_TEST)
    .bind(dataset_id)
    .bind(filename)
    .bind(DIGEST)
    .execute(connection)
    .await
}
