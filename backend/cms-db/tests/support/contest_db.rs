//! The `contests` scratch schema and inserts the live suites share.

use chrono::{NaiveDate, NaiveDateTime};
use cms_db::{ContestWindow, DedicatedConnection, Interval, SessionConfig, TokenMode, TokenPolicy};
use sqlx::postgres::{PgConnection, PgQueryResult};

/// The environment variable naming the scratch database.
pub const URL_ENV: &str = "CMS_DB_TEST_URL";

/// The three stored modes, created once per scratch database.
const CREATE_TYPE: &str = "\
    DO $$ BEGIN \
        CREATE TYPE token_mode AS ENUM ('disabled', 'finite', 'infinite'); \
    EXCEPTION WHEN duplicate_object THEN NULL; \
    END $$";

/// `contests` with the columns and checks the live suites exercise.
const CREATE_CONTESTS: &str = "\
    CREATE TEMP TABLE contests (\
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
        name text NOT NULL UNIQUE, \
        start timestamp NOT NULL, \
        stop timestamp NOT NULL, \
        analysis_enabled boolean NOT NULL, \
        analysis_start timestamp NOT NULL, \
        analysis_stop timestamp NOT NULL, \
        token_mode token_mode NOT NULL DEFAULT 'infinite', \
        token_max_number integer CHECK (token_max_number > 0), \
        token_min_interval interval NOT NULL DEFAULT interval '0 seconds' \
            CHECK (token_min_interval >= interval '0 seconds'), \
        token_gen_initial integer NOT NULL DEFAULT 2 \
            CHECK (token_gen_initial >= 0), \
        token_gen_number integer NOT NULL DEFAULT 2 \
            CHECK (token_gen_number >= 0), \
        token_gen_interval interval NOT NULL DEFAULT interval '30 minutes' \
            CHECK (token_gen_interval > interval '0 seconds'), \
        token_gen_max integer CHECK (token_gen_max > 0), \
        CHECK (start <= stop), \
        CHECK (stop <= analysis_start), \
        CHECK (analysis_start <= analysis_stop), \
        CHECK (token_gen_initial <= token_gen_max))";

/// Serialises the one catalogue write every test shares; the DO block's handler
/// catches the already-exists error, not the unique-index race two connections
/// can hit at once.
const LOCK_TYPE: &str = "SELECT pg_advisory_lock(918273)";
const UNLOCK_TYPE: &str = "SELECT pg_advisory_unlock(918273)";

/// The scratch database, or a printed skip when none is configured.
pub fn skip() -> Option<SessionConfig> {
    let config = std::env::var(URL_ENV)
        .ok()
        .filter(|url| !url.trim().is_empty())
        .map(SessionConfig::new);
    if config.is_none() {
        eprintln!("SKIP: set {URL_ENV} to a scratch database to run the live half");
    }
    config
}

/// Open the scratch database and create the contest schema on it.
pub async fn open(config: &SessionConfig) -> DedicatedConnection {
    let mut connection = DedicatedConnection::open(config)
        .await
        .expect("opening the scratch database");
    for statement in [LOCK_TYPE, CREATE_TYPE, UNLOCK_TYPE, CREATE_CONTESTS] {
        sqlx::query(statement)
            .execute(connection.connection())
            .await
            .expect("creating the contests schema");
    }
    connection
}

/// The SQLSTATE of a refused statement, so a refusal is pinned to its own rule.
pub fn code_of<T>(result: &Result<T, sqlx::Error>) -> Option<String> {
    result
        .as_ref()
        .err()
        .and_then(sqlx::Error::as_database_error)
        .and_then(|error| error.code())
        .map(|code| code.to_string())
}

/// One instant on the day every fixture sits on.
pub fn at(hour: u32, minute: u32) -> NaiveDateTime {
    NaiveDate::from_ymd_opt(2026, 11, 22)
        .and_then(|date| date.and_hms_opt(hour, minute, 0))
        .expect("fixture time is valid")
}

/// A contest open from 09:00 to 12:00, with analysis from 13:00 to 14:00.
pub fn window() -> ContestWindow {
    ContestWindow {
        start: at(9, 0),
        stop: at(12, 0),
        analysis_enabled: true,
        analysis_start: at(13, 0),
        analysis_stop: at(14, 0),
    }
}

/// A policy inside every token check.
pub fn policy() -> TokenPolicy {
    TokenPolicy {
        mode: TokenMode::Finite,
        max_number: Some(10),
        min_interval: Interval::from_seconds(60).expect("fixture interval"),
        gen_initial: 2,
        gen_number: 1,
        gen_interval: Interval::from_seconds(600).expect("fixture interval"),
        gen_max: Some(4),
    }
}

/// Insert one window under a unique name.
pub async fn insert_window(
    connection: &mut PgConnection,
    name: &str,
    window: &ContestWindow,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO contests \
         (name, start, stop, analysis_enabled, analysis_start, analysis_stop) \
         VALUES ($1, $2, $3, $4, $5, $6)",
    )
    .bind(name)
    .bind(window.start)
    .bind(window.stop)
    .bind(window.analysis_enabled)
    .bind(window.analysis_start)
    .bind(window.analysis_stop)
    .execute(connection)
    .await
}

/// Insert one token policy under a unique name.
pub async fn insert_policy(
    connection: &mut PgConnection,
    name: &str,
    policy: &TokenPolicy,
) -> Result<PgQueryResult, sqlx::Error> {
    sqlx::query(
        "INSERT INTO contests \
         (name, start, stop, analysis_enabled, analysis_start, analysis_stop, \
          token_mode, token_max_number, token_min_interval, token_gen_initial, \
          token_gen_number, token_gen_interval, token_gen_max) \
         VALUES ($1, timestamp '2026-11-22 09:00', timestamp '2026-11-22 12:00', false, \
                 timestamp '2026-11-22 13:00', timestamp '2026-11-22 14:00', \
                 $2::token_mode, $3, $4, $5, $6, $7, $8)",
    )
    .bind(name)
    .bind(policy.mode.as_str())
    .bind(policy.max_number)
    .bind(policy.min_interval.to_pg().expect("fixture interval fits"))
    .bind(policy.gen_initial)
    .bind(policy.gen_number)
    .bind(policy.gen_interval.to_pg().expect("fixture interval fits"))
    .bind(policy.gen_max)
    .execute(connection)
    .await
}
