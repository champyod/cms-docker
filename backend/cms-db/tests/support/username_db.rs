//! The five display-username tables as the Prisma migrations create them, and the
//! rows the live suites ask about.
//!
//! Every table is `TEMP`, so each test owns its copy in its own connection. The
//! two policy enums are database-scoped and created once, guarded the way the
//! contest suite guards `token_mode`.

use chrono::{NaiveDate, NaiveDateTime};
use cms_db::{Codename, Interval, Participation, PasswordForm, SessionConfig, User};
use sqlx::postgres::PgConnection;
use sqlx::Connection;

/// The environment variable naming the scratch database.
pub const URL_ENV: &str = "CMS_DB_TEST_URL";

/// The two enums `username_policies` is declared with.
const CREATE_TYPES: &str = "\
    DO $$ BEGIN
        CREATE TYPE username_policy_scope AS ENUM ('contest', 'user', 'group');
    EXCEPTION WHEN duplicate_object THEN NULL;
    END $$;
    DO $$ BEGIN
        CREATE TYPE username_policy AS ENUM ('allow', 'deny');
    EXCEPTION WHEN duplicate_object THEN NULL;
    END $$";

/// Serialises the one catalogue write every test shares.
const LOCK_TYPES: &str = "SELECT pg_advisory_lock(918274)";
const UNLOCK_TYPES: &str = "SELECT pg_advisory_unlock(918274)";

/// The five tables, with the uniqueness the migrations declare on each.
const CREATE_TABLES: &[&str] = &[
    "CREATE TEMP TABLE username_policies (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scope username_policy_scope NOT NULL,
        scope_id integer NOT NULL,
        policy username_policy NOT NULL,
        updated_at timestamp NOT NULL DEFAULT now(),
        updated_by integer)",
    "CREATE UNIQUE INDEX ON username_policies (scope, scope_id)",
    "CREATE TEMP TABLE contestant_group_memberships (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id integer NOT NULL,
        group_id integer NOT NULL,
        created_at timestamp NOT NULL DEFAULT now())",
    "CREATE UNIQUE INDEX ON contestant_group_memberships (user_id, group_id)",
    "CREATE TEMP TABLE contest_usernames (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        participation_id integer NOT NULL,
        contest_id integer NOT NULL,
        user_id integer NOT NULL,
        username varchar NOT NULL,
        updated_at timestamp NOT NULL DEFAULT now(),
        updated_by_admin_id integer)",
    "CREATE UNIQUE INDEX contest_usernames_participation_id_key
        ON contest_usernames (participation_id)",
    "CREATE UNIQUE INDEX contest_usernames_contest_id_username_key
        ON contest_usernames (contest_id, username)",
    "CREATE TEMP TABLE contest_usernames_history (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        contest_id integer NOT NULL,
        user_id integer NOT NULL,
        username varchar,
        set_at timestamp NOT NULL DEFAULT now(),
        set_by_admin_id integer)",
];

/// The scratch database's URL, or a printed skip when none is configured.
pub fn skip() -> Option<SessionConfig> {
    let config = std::env::var(URL_ENV)
        .ok()
        .filter(|url| !url.trim().is_empty())
        .map(SessionConfig::new);
    if config.is_none() {
        eprintln!("SKIP: set {URL_ENV} to a scratch database to run the live half");
    }
    config
}

/// A connection whose temp schema holds the five tables, empty.
pub async fn open(config: &SessionConfig) -> PgConnection {
    let mut connection = PgConnection::connect(&config.url)
        .await
        .expect("connecting to the scratch database");
    sqlx::query(LOCK_TYPES)
        .execute(&mut connection)
        .await
        .expect("locking the type catalogue");
    sqlx::raw_sql(CREATE_TYPES)
        .execute(&mut connection)
        .await
        .expect("creating the policy enums");
    sqlx::query(UNLOCK_TYPES)
        .execute(&mut connection)
        .await
        .expect("unlocking the type catalogue");
    for statement in CREATE_TABLES {
        sqlx::raw_sql(sqlx::AssertSqlSafe(*statement))
            .execute(&mut connection)
            .await
            .expect("creating the display-username schema");
    }
    connection
}

/// A policy row at one scope.
pub async fn policy(connection: &mut PgConnection, scope: &str, scope_id: i32, verdict: &str) {
    sqlx::query(
        "INSERT INTO username_policies (scope, scope_id, policy) \
         VALUES ($1::username_policy_scope, $2, $3::username_policy)",
    )
    .bind(scope)
    .bind(scope_id)
    .bind(verdict)
    .execute(connection)
    .await
    .expect("inserting a policy row");
}

/// A contestant group membership.
pub async fn membership(connection: &mut PgConnection, user_id: i32, group_id: i32) {
    sqlx::query("INSERT INTO contestant_group_memberships (user_id, group_id) VALUES ($1, $2)")
        .bind(user_id)
        .bind(group_id)
        .execute(connection)
        .await
        .expect("inserting a membership row");
}

/// The participation a fixture writes an alias for.
#[must_use]
pub fn participation(contest_id: i32, user_id: i32) -> Participation {
    Participation {
        id: user_id + 100 * contest_id,
        ip: None,
        starting_time: None,
        delay_time: Interval::zero(),
        extra_time: Interval::zero(),
        password: None,
        hidden: false,
        unrestricted: false,
        contest_id,
        user_id,
        team_id: None,
    }
}

/// The user a fixture shows a name for.
#[must_use]
pub fn user(id: i32, first_name: &str, last_name: &str) -> User {
    User {
        id,
        first_name: first_name.to_owned(),
        last_name: last_name.to_owned(),
        username: Codename::parse(&format!("user{id}")).expect("a valid codename"),
        password: PasswordForm::parse("plaintext:fixture").expect("a stored row"),
        email: None,
        timezone: None,
        preferred_languages: Vec::new(),
        last_login_at: None,
    }
}

/// A timestamp the history rows are written with.
#[must_use]
pub fn at(hour: u32, minute: u32) -> NaiveDateTime {
    NaiveDate::from_ymd_opt(2026, 11, 22)
        .and_then(|date| date.and_hms_opt(hour, minute, 0))
        .expect("a valid fixture time")
}

/// A codename, for the aliases the suites set.
#[must_use]
pub fn codename(value: &str) -> Codename {
    Codename::parse(value).expect("a valid codename")
}
