//! Which teams a contest offers, against a real server.
//!
//! WHY live: the rule is a `COALESCE` over an outer join, so the case that matters —
//! a team with no `contest_teams` row for this contest — is a join behaviour only the
//! server can show. The tables are `TEMP`, so a run leaves the scratch database as it
//! found it.
//!
//! RUN: CMS_DB_TEST_URL=postgres://cmsuser:***@127.0.0.1:5432/cmsdb_test \
//!        cargo test -p cms-db --test teams_live

use cms_db::{registerable_teams, SessionConfig};
use sqlx::postgres::PgConnection;
use sqlx::Connection;

const URL_ENV: &str = "CMS_DB_TEST_URL";

const CONFIGURED: i32 = 1;
const UNCONFIGURED: i32 = 2;

/// `teams` and the contest roster that overrides it, as the reference declares them.
const TABLES: &[&str] = &[
    "CREATE TEMP TABLE teams (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code varchar NOT NULL UNIQUE,
        name varchar NOT NULL,
        registerable boolean NOT NULL DEFAULT true)",
    "CREATE TEMP TABLE contest_teams (
        contest_id integer NOT NULL,
        team_id integer NOT NULL,
        registerable boolean NOT NULL DEFAULT true,
        PRIMARY KEY (contest_id, team_id))",
];

/// The teams every test starts from: one offered everywhere, one withdrawn by default.
const TEAMS: &str = "\
    INSERT INTO teams (id, code, name, registerable) VALUES
        (1, 'ita', 'Italy', true),
        (2, 'fra', 'France', false),
        (3, 'sui', 'Switzerland', true)";

fn skip() -> Option<SessionConfig> {
    let config = std::env::var(URL_ENV)
        .ok()
        .filter(|url| !url.trim().is_empty())
        .map(SessionConfig::new);
    if config.is_none() {
        eprintln!("SKIP: set {URL_ENV} to a scratch database to run the live half");
    }
    config
}

async fn open(config: &SessionConfig) -> PgConnection {
    let mut connection = PgConnection::connect(&config.url)
        .await
        .expect("connecting to the scratch database");
    for statement in TABLES {
        sqlx::raw_sql(sqlx::AssertSqlSafe(*statement))
            .execute(&mut connection)
            .await
            .expect("creating the team schema");
    }
    sqlx::raw_sql(TEAMS)
        .execute(&mut connection)
        .await
        .expect("seeding the teams");
    connection
}

async fn override_registerable(
    connection: &mut PgConnection,
    contest_id: i32,
    team_id: i32,
    value: bool,
) {
    sqlx::query(
        "INSERT INTO contest_teams (contest_id, team_id, registerable) VALUES ($1, $2, $3)",
    )
    .bind(contest_id)
    .bind(team_id)
    .bind(value)
    .execute(connection)
    .await
    .expect("writing a roster row");
}

#[tokio::test]
async fn a_team_with_no_contest_row_falls_back_to_its_own_flag() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;

    let offered = registerable_teams(&mut connection, UNCONFIGURED)
        .await
        .expect("the roster reads");
    let ids: Vec<i32> = offered.iter().map(|team| team.id).collect();
    assert_eq!(ids, vec![1, 3], "France's own flag keeps it out");
    assert_eq!(offered[0].code.as_str(), "ita");
    assert!(offered[0].registerable);
}

#[tokio::test]
async fn a_contest_row_overrides_the_team_flag_in_both_directions() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    override_registerable(&mut connection, CONFIGURED, 1, false).await;
    override_registerable(&mut connection, CONFIGURED, 2, true).await;

    let ids: Vec<i32> = registerable_teams(&mut connection, CONFIGURED)
        .await
        .expect("the roster reads")
        .iter()
        .map(|team| team.id)
        .collect();
    assert_eq!(
        ids,
        vec![2, 3],
        "the roster row decides, not the team's own flag"
    );
}

#[tokio::test]
async fn a_contest_row_decides_only_for_its_own_contest() {
    let Some(config) = skip() else {
        return;
    };
    let mut connection = open(&config).await;
    override_registerable(&mut connection, CONFIGURED, 3, false).await;

    let configured: Vec<i32> = registerable_teams(&mut connection, CONFIGURED)
        .await
        .expect("the roster reads")
        .iter()
        .map(|team| team.id)
        .collect();
    let unconfigured: Vec<i32> = registerable_teams(&mut connection, UNCONFIGURED)
        .await
        .expect("the roster reads")
        .iter()
        .map(|team| team.id)
        .collect();
    assert_eq!(configured, vec![1]);
    assert_eq!(
        unconfigured,
        vec![1, 3],
        "another contest keeps the fallback"
    );
}
