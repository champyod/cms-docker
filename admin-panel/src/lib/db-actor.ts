import { AsyncLocalStorage } from 'node:async_hooks';

/**
 * Who a database transaction acts as.
 *
 * WHY this exists at all: every table carries FORCE ROW LEVEL SECURITY, but the policies were
 * `USING (true)`, so the database enforced nothing. They now read `cms.actor` — a transaction-local
 * GUC — so a connection that has not said who it is can read no row and write none. That makes the
 * actor the one thing every query path has to supply, and this module is the only place that says
 * what a valid actor is.
 *
 * The shape is deliberately the same as the SQL side:
 *   `admin:<id>`    a signed-in panel admin.
 *   `system:<name>` a named, non-human identity, listed in {@link SYSTEM_IDENTITIES}.
 * The SQL helpers (`public.cms_actor_*`, generated by scripts/__generate_rls_sql.sh) accept nothing
 * else; an unparseable value reads as "no actor" there, so a typo would silently produce an empty
 * result set. That is why {@link actorClaim} refuses to format one and why the resolution below
 * throws instead of guessing.
 *
 * WHY NO FALLBACK: the whole point of moving enforcement into the database is that a forgotten
 * call site must fail closed. "No actor means allow" is exactly the defect this replaces, so a
 * missing actor raises {@link MissingDbActorError} — loud at the call site, and empty at the row
 * level if anything ever bypasses this check.
 */

/** The named non-human identities. Restated in the generator's allowlists; see the migration. */
export const SYSTEM_IDENTITIES = {
  /** Pre-session login: verifying a credential and resolving its grants. */
  AUTH: 'system:auth',
  /** `./cms panel` and scripts/__panel_action.sh — a script-side write. */
  CLI: 'system:cli',
  /** The security feed's HTTP push; may only append and update findings. */
  INGEST: 'system:ingest',
  /** Seeding and migrations. */
  MIGRATION: 'system:migration',
  /** The backup scheduler process (src/scheduler/main.ts): it starts and settles backup runs with
   *  no request and no cookie, so it names itself rather than borrowing a human identity. */
  SCHEDULER: 'system:scheduler',
  /** The audit-log retention service (scripts/audit-log.ts prune): the only identity the database
   *  lets prune `audit_log`, and only rows older than public.cms_audit_retention_cutoff(). It is
   *  deliberately not in the staff set: it reads the log and shortens it, nothing else. */
  AUDIT_RETENTION: 'system:audit-retention',
} as const;

export type SystemIdentity = (typeof SYSTEM_IDENTITIES)[keyof typeof SYSTEM_IDENTITIES];

export type DbActor =
  | { readonly kind: 'admin'; readonly id: number }
  | { readonly kind: 'system'; readonly name: SystemIdentity };

export const SYSTEM_ACTOR_NAMES: readonly string[] = Object.values(SYSTEM_IDENTITIES);

/** Raised when a query runs with no identity. Never caught to supply a default. */
export class MissingDbActorError extends Error {
  constructor(detail: string) {
    super(
      `no database actor: ${detail}. Every table is row-level secured on cms.actor, so this query ` +
        'would read nothing and write nothing — wrap the scope in withActor() (a signed-in panel ' +
        'request resolves its own actor from the session cookie).',
    );
    this.name = 'MissingDbActorError';
  }
}

/** The GUC value for an actor: `admin:<id>` or `system:<name>`. */
export function actorClaim(actor: DbActor): string {
  if (actor.kind === 'admin') {
    if (!Number.isInteger(actor.id) || actor.id <= 0) {
      throw new MissingDbActorError(`admin actor id ${String(actor.id)} is not a positive integer`);
    }
    return `admin:${actor.id}`;
  }
  if (!SYSTEM_ACTOR_NAMES.includes(actor.name)) {
    throw new MissingDbActorError(`unknown system identity ${String(actor.name)}`);
  }
  return actor.name;
}

/**
 * The chain a scope's identity is carried on.
 *
 * WHY AsyncLocalStorage and not a module variable: the panel serves concurrent requests from one
 * process, and a module-level "current actor" would be overwritten by whichever request spoke last
 * — the cross-request leak this whole change exists to prevent, moved from the connection into
 * JavaScript. ALS is per async context, so two overlapping requests cannot see each other's actor.
 */
type ActorStore = { actor: DbActor };

// Exported for db-actor-request.ts, the module that reads the session cookie: the scope itself must
// stay here, because this file is what non-request processes (scheduler, CLI, the image smoke check)
// can import safely — it has no dependency on next/headers.
export const actorStorage = new AsyncLocalStorage<ActorStore>();

/** The actor of the current scope, if one was established. */
export function currentDbActor(): DbActor | undefined {
  return actorStorage.getStore()?.actor;
}

/**
 * Run `fn` as `actor`. Every database call inside it — including every statement of a Prisma
 * interactive transaction — carries that identity, and nothing outside it does.
 *
 * WHY a scope and not a per-call argument: 141 modules import the client, and threading an actor
 * through each signature would leave the one that was missed reading everything. A scope makes the
 * identity a property of the work, so a new module inherits the caller's identity instead of
 * having to remember one.
 */
export function withActor<T>(actor: DbActor, fn: () => PromiseLike<T>): Promise<T> {
  // Validated before the scope opens: a malformed identity must fail here, not at the first query.
  actorClaim(actor);
  return actorStorage.run({ actor }, async () => await fn());
}
